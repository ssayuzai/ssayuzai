def _is_duplicate(error: Exception) -> bool:
    """'이미 있는 값' 오류인지 알아봐요. (Postgres 는 오류 번호 23505 예요)"""
    return isinstance(error, sqlite3.IntegrityError) or "23505" in str(error)


def create_user(username: str, password_hash: str) -> int | None:
    """회원을 만들고 번호를 돌려줘요. 이미 있는 아이디면 None 을 돌려줘요."""
    try:
        with connect() as conn:
            cursor = _run(
                conn,
                "INSERT INTO users (username, password_hash, created_at) VALUES (?, ?, ?) RETURNING id",
                (username, password_hash, _now()),
            )
            return cursor.fetchone()[0]
    except Exception as e:
        if _is_duplicate(e):
            return None
        raise


def find_user(username: str) -> dict | None:
    with connect() as conn:
        return _one(_run(conn, "SELECT * FROM users WHERE lower(username) = lower(?)", (username,)))


def get_user(user_id: int) -> dict | None:
    with connect() as conn:
        return _one(_run(conn, "SELECT * FROM users WHERE id = ?", (user_id,)))


